# 注入数据的总字节预算（约对应安全的 token 量）。仅按条数 _trim 仍可能因单条过长超限，
# 这里加总长度兜底：超限则截断并显著标注，避免静默把上下文撑爆导致请求失败或前段被挤掉。
_MAX_INJECT_CHARS = 60000
# 问答 messages 跨段总字符预算（system+history+user）。免费小上下文模型超限只会返回
# 误导性 4xx，故在组装层封顶：超出先砍最旧历史。中文 token 密度高，48k 字符约对应安全 token 量。
_MAX_TOTAL_CHARS = 48000
# 单条用户消息上限：超长截断并标注，避免不限长 message 直接撑爆窗口。
_MAX_USER_CHARS = 8000


# 列式编码里 None/缺失字段的统一占位。免费小模型读散文/JSON 都比读列表费 token，
# 把"个股×多字段"这类记录数组改成『表头出现一次 + 每行只列值』的 markdown 表，
# 键名不再逐行重复，是本项削减的主要来源。占位符必须显式区别于 0：空单元格会被模型
# 当 0 读（数据真实性问题），故缺失值一律渲染为 _NULL，并在表前声明其含义。
_NULL = "—"
# 单条记录字段数≥该阈值的同构 list[dict] 才转表（短数组转表反而多出分隔线，得不偿失）。
_TABLE_MIN_FIELDS = 3


def _cell(v) -> str:
    """渲染单元格：None→缺失占位（绝不留空被当 0）；列表/字典转紧凑 JSON 串保形。"""
    if v is None:
        return _NULL
    if isinstance(v, bool):
        return "是" if v else "否"
    if isinstance(v, (list, dict)):
        return json.dumps(v, ensure_ascii=False, default=str)
    s = str(v)
    # 单元格内禁止裸竖线/换行，否则破坏 markdown 表格列对齐
    return s.replace("|", "/").replace("\n", " ")


def _is_record_table(v) -> bool:
    """v 是否为可转 markdown 表的同构记录数组：非空 list[dict]，且并集字段数达阈值。"""
    if not isinstance(v, list) or not v:
        return False
    if not all(isinstance(x, dict) for x in v):
        return False
    keys: set = set()
    for x in v:
        keys.update(x.keys())
    return len(keys) >= _TABLE_MIN_FIELDS


def _record_table(rows: list[dict]) -> str:
    """同构记录数组 → markdown 表。列顺序取首行键序、再并入后续行出现的新键，
    保证字段顺序稳定且不丢任何字段；缺该字段的行该格填缺失占位。"""
    cols: list[str] = []
    for r in rows:
        for k in r.keys():
            if k not in cols:
                cols.append(k)
    head = "| " + " | ".join(cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    lines = [head, sep]
    for r in rows:
        lines.append("| " + " | ".join(_cell(r.get(c)) for c in cols) + " |")
    return "\n".join(lines)


def _encode(data, _depth: int = 0) -> str:
    """把注入数据编码成对小模型友好且省 token 的紧凑文本：
    - 同构记录数组（涨停池/板块/涨幅榜/资金流/持仓等）→ markdown 表（表头只出现一次）；
    - 字符串数组（missing 缺失标注、新闻条目等）→ 逐行 - 列表（一字不丢）；
    - 标量/嵌套对象 → JSON（保形，避免破坏 quote/总览这类键值结构的可读性）。
    全程不丢任何字段与数值，None 统一渲染为缺失占位（见 _NULL）。"""
    if isinstance(data, dict):
        # 标题层级随嵌套深度加深（## → ### → …），让段落结构在小模型侧也清晰
        hx = "#" * min(_depth + 2, 6)
        parts: list[str] = []
        for k, v in data.items():
            if _is_record_table(v):
                parts.append(f"{hx} {k}\n{_record_table(v)}")
            elif isinstance(v, list) and v and all(not isinstance(x, (dict, list)) for x in v):
                # 字符串/标量数组（典型：missing、新闻标题列表）→ 列表，逐条保留
                body = "\n".join(f"- {_cell(x)}" for x in v)
                parts.append(f"{hx} {k}\n{body}")
            elif isinstance(v, dict):
                parts.append(f"{hx} {k}\n{_encode(v, _depth + 1)}")
            else:
                # 标量、空数组、含嵌套结构的混合数组 → JSON 保形
                parts.append(f"- {k}: {json.dumps(v, ensure_ascii=False, default=str)}")
        return "\n".join(parts)
    # 顶层非 dict（理论上不会发生）兜底 JSON
    return json.dumps(data, ensure_ascii=False, default=str)


def _round_floats(obj):
    """注入 AI 前把浮点数取整到 2 位小数：去掉 -4088000000.0000005 这类计算浮点噪声，
    整值再转 int 更干净。仅用于注入展示、不参与任何计算（铁律：只去噪、不改数值量级）。"""
    if isinstance(obj, float):
        try:
            r = round(obj, 2)
            return int(r) if r == int(r) else r
        except (ValueError, OverflowError):  # nan/inf 原样透出
            return obj
    if isinstance(obj, dict):
        return {k: _round_floats(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_round_floats(x) for x in obj]
    return obj


# ---- 资金类大额数字人性化（元 → 亿/万元），注入 AI 前确定性预格式化 ----
# 客户反馈：报告正文出现「电子主力净流入 23319080960」这种裸元数字，人看不懂。
# 根因：_round_floats 只去浮点噪声、不动大整数 → 资金净额(元)原样喂给 AI、AI 照抄。
# 这里在注入前把【资金类字段】的大额元值确定性换算成「233.19亿元」字符串——
# 只改展示单位、绝不改数值量级（铁律明确允许「金额展示可换算亿元/万元」），AI 只是照读。
# 严格按【字段名】白名单命中，且只动数字、|值|≥1万 的；价/换手/涨跌幅/量/比率/占比一律不碰。
_MONEY_KEY_HINTS = (
    "净流入", "净流出", "净额", "净买", "主力", "资金", "成交额", "成交金额", "金额",
    "净流", "流入", "流出", "市值", "总市值", "流通市值",
    "net_amount", "net_buy", "net_inflow", "net_outflow", "main_net", "main_flow",
    "inflow", "outflow", "amount_net", "turnover_amount", "total_mv", "circ_mv",
    # 个股盘口/资金流常见英文键（均为【元】）：成交额 amount、流通市值 float_mv、
    # 各档净额 *_net（super_net/large_net/medium_net/small_net）——覆盖诊断证据链/问股每处。
    "amount", "float_mv", "_net",
)
# 命中名单后仍需排除的：避免误伤「资金占比%/资金强度/换手率」这类非元字段
_MONEY_KEY_EXCLUDE = ("占比", "比例", "强度", "率", "pct", "ratio", "rate", "rank", "排名", "倍")


def _fmt_money_cn(n: float) -> str:
    """元 → 人性化『亿/万元』字符串（带负号），与前端 fmtMoney 对齐。仅展示、不参与计算。"""
    sign = "-" if n < 0 else ""
    a = abs(n)
    if a >= 1e12:
        return f"{sign}{a / 1e12:.2f}万亿元"
    if a >= 1e8:
        return f"{sign}{a / 1e8:.2f}亿元"
    if a >= 1e4:
        return f"{sign}{a / 1e4:.1f}万元"
    return f"{sign}{a:.0f}元"


def _is_money_key(k) -> bool:
    ks = str(k)
    if any(x in ks for x in _MONEY_KEY_EXCLUDE):
        return False
    return any(h in ks for h in _MONEY_KEY_HINTS)


def _humanize_amounts(obj):
    """递归把『资金类字段』的大额元数值换算成「亿/万元」字符串（注入展示用）。
    只认：字段名命中 _MONEY_KEY_HINTS、值为 int/float（非 bool）、|值|≥1万 的；
    其余字段（价/换手/涨跌幅/量/比率/占比）一律原样透出。铁律：只改单位展示、不改量级。"""
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if (_is_money_key(k) and isinstance(v, (int, float))
                    and not isinstance(v, bool) and abs(v) >= 1e4):
                out[k] = _fmt_money_cn(float(v))
            else:
                out[k] = _humanize_amounts(v)
        return out
    if isinstance(obj, list):
        return [_humanize_amounts(x) for x in obj]
    return obj


def _inject(data: dict) -> str:
    """把真实数据以列式/markdown 表编码注入提示词，带总长度预算。
    （历史为整体 json.dumps，记录数组逐行重复键名极费 token；列式编码后表头只出现一次，
    免费小模型解析也更稳。仍保留全部数值/单位与 missing 标注，缺失值显式占位不冒充 0。）"""
    payload = _encode(_humanize_amounts(_round_floats(data)))
    if len(payload) > _MAX_INJECT_CHARS:
        payload = (
            payload[:_MAX_INJECT_CHARS]
            + f"\n…（注入数据超过 {_MAX_INJECT_CHARS} 字符已截断，部分明细未包含，分析时注意数据可能不完整）"
        )
    return (
        "\n\n【注入的真实数据（唯一可引用来源）】\n"
        f"（下方为列式编码：## 段名 + markdown 表/列表；表中 “{_NULL}” 表示该字段数据不全/缺失，"
        "绝不可当 0 解读。所有数值/单位均为原值。\n"
        "资金/市值类大额已自动换算为「亿元/万元」字符串（如“233.19亿元”）便于阅读——直接照引该字符串，"
        "勿再展开成裸位数；引用百分比一律保留不超过 2 位小数。）\n"
        + payload
        + "\n"
    )


def _knowledge_block(digest: str) -> str:
    if not digest:
        return ""
    return (
        "\n【用户个人交易知识库摘要（结合用户风格提醒操作）】\n" + digest + "\n"
    )


# 客户专属「高手蒸馏」追加块（off-by-default）。默认空串 → system prompt 一字不变；
# 仅当某客户 config 配了 persona.masters 时，main.py 启动期调 set_persona_extra() 注入。
# 母项目通用能力：任何客户都能在自己 config 里加蒸馏规则，客户之间互不影响、共享代码无分支逻辑。
_PERSONA_EXTRA = ""


def set_persona_extra(text: str) -> None:
    """启动期由 main.py 按客户 config 调用一次。未配置的客户永不调用 → 行为不变。"""
    global _PERSONA_EXTRA
    _PERSONA_EXTRA = str(text or "").strip()


def _persona_extra_block() -> str:
    if not _PERSONA_EXTRA:
        return ""
    return "\n◆ 本客户专属蒸馏（额外高手判断规则，与上方规则库同等权重参考）：\n" + _PERSONA_EXTRA + "\n"


# 本客户「输出准则」：比 persona 更硬——强制每条研报/问股/诊断/持仓处理的结论形态
# （全面→讲为什么→强推荐(价格+动作+股数)→不追涨停）。母项目通用、off-by-default：未配置的客户
# （如三势那种要条件化、区分事实/判断的客户）一字不变。优先级仍【低于】数据真实性铁律——
# 强推荐 ≠ 编价：数据缺照样标缺、绝不为"显得果断"造数。
_OUTPUT_DIRECTIVE = ""


def set_output_directive(text: str) -> None:
    """启动期由 main.py 按客户 config.output_directive 调用一次。未配置 → 永不注入、行为不变。"""
    global _OUTPUT_DIRECTIVE
    _OUTPUT_DIRECTIVE = str(text or "").strip()


def _output_directive_block() -> str:
    if not _OUTPUT_DIRECTIVE:
        return ""
    return ("\n【本客户输出准则·高优先级·每条结论都要照做（但绝不得违反上方数据真实性铁律）】\n"
            + _OUTPUT_DIRECTIVE + "\n")


def system_prompt(knowledge_digest: str = "") -> str:
    return PERSONA + _persona_extra_block() + _output_directive_block() + _knowledge_block(knowledge_digest)


